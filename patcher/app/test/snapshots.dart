/// The user's own installation, read in place.
Map<String, dynamic> localGame({
  String state = 'installed',
  String title = 'Ready to play',
  String status = 'Ready to play',
  String play = 'available',
  String? reason,
  String? primary = 'Launch',
  bool progress = false,
  List<String>? actions,
  Map<String, String> labels = const {},
  Map<String, String> unavailable = const {},
  Map<String, dynamic> extra = const {},
}) {
  final offered = [
    if (play == 'available') 'Launch',
    ...(actions ?? ['SetPolicy', 'ViewPacks']),
  ];
  return {
    'revision': 1,
    'state': state,
    'phase': state,
    'title': title,
    'status': status,
    'detail': '2 of 106 packs installed, 4.6 GB on disk.',
    'path': '/home/me/.local/share/Steam/steamapps/common/The Sims 4',
    'fixture': false,
    'ready': false,
    'bytes_done': 3072,
    'bytes_total': 10240,
    'bytes_per_second': 1024,
    'files_done': 3,
    'files_total': 10,
    'show_progress': progress,
    'details': [],
    'actions': offered,
    'primary': primary,
    'labels': {for (final a in offered) a: labels[a] ?? defaultLabels[a] ?? a},
    'unavailable': {
      'CheckAppUpdate': notInstalledByInstaller,
      if (play == 'unavailable' && reason != null) 'Launch': reason,
      ...unavailable,
    },
    'play': play,
    'play_reason': reason,
    'packs': localPacks(),
    'collection': '2 of 4 packs installed - 1 is missing files',
    'candidates': [],
    'checked': [],
    'policy_revision': 3,
    'online': 'Unavailable: sign-in handoff is not validated',
    'preferences': {
      'future_packs': false,
      'background': false,
      'metered': false,
      'bandwidth_bytes_per_second': 0,
    },
    'language': 'ENG_US',
    'languages': ['ENG_US', 'GER_DE'],
    'app_update': null,
    'app_update_status': null,
    'error': null,
    'next_action': '',
    'downloads_supported': false,
    'background_supported': false,
    'background_note': null,
    'mode_note':
        'The patcher reads your game folder and never changes game files.',
    'checked_at': '2026-11-10 08:00 UTC',
    ...extra,
  };
}

